/* Extracts the icons the game uses from the game-icons.net set (CC BY 3.0) into js/icons.js,
   and writes the per-icon author list used in CREDITS.md. Needs @iconify-json/game-icons and a
   listing of the game-icons/icons repository (author/name.svg) in tools/icon-authors.txt. */
const fs = require('fs'), path = require('path');
const map = require('./iconmap.js');
const set = require(process.env.ICONSET || '@iconify-json/game-icons/icons.json');   // npm i --no-save @iconify-json/game-icons, or point ICONSET at icons.json
const authors = {};
for (const line of fs.readFileSync(path.join(__dirname, 'icon-authors.txt'), 'utf8').split('\n')) { const m = line.match(/^([^/]+)\/([^/]+)\.svg$/); if (m) authors[m[2]] = m[1]; }
const out = {}, used = {};
for (const key in map) {
  const name = map[key], ic = set.icons[name];
  if (!ic) throw new Error('icon not found: ' + name);
  const paths = [...ic.body.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error('no path in ' + name);
  out[key] = paths.join(' ');
  used[name] = authors[name] || 'unknown';
}
fs.writeFileSync(path.join(__dirname, '..', 'js', 'icons.js'), '/* Icons from game-icons.net, CC BY 3.0. Authors are listed in CREDITS.md. Generated by tools/icons.js. */\nwindow.ICONS = ' + JSON.stringify(out) + ';\n');
const by = {};
for (const n in used) (by[used[n]] = by[used[n]] || []).push(n);
fs.writeFileSync(path.join(__dirname, 'icon-credits.json'), JSON.stringify(by, null, 1));
console.log(Object.keys(out).length + ' icons, ' + (JSON.stringify(out).length / 1024).toFixed(0) + ' KB, authors: ' + Object.keys(by).map((a) => a + ' ' + by[a].length).join(', '));
